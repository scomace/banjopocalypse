// WORLD 2: THE FLOODED MEGA-MART. 11 original layouts, still friendly.
// Motifs: long shelf runs like store aisles, water-current wind lanes
// between the shelving, the occasional smear of broken display glass,
// boss tank at 11.
// Grid: 30 wide x 17 tall. See levels/types.ts for symbols.
//
// THE TIER GRID — read this before editing any layout.
// Platforms go ONLY on rows 13 / 10 / 7 / 4 (and 1 for attic levels). That is
// 3 rows = 96px apart, and the weakest jumper in the cast rises 116px, so every
// step has ~20px of slack. Each tier must overlap — or sit within ~2 columns
// of — a tier one step below it, or the player is stranded on the floor
// watching enemies come down to them. Spawn markers (a-d, J, S, W) go on the
// row directly ABOVE their platform; player spawns go on row 15.
//
// Anything 4+ rows up is deliberate: that is what bubbles are for. Ride one to
// climb, or bounce off one (hold jump on contact) for a ~5 tile launch.
//
// `npx tsx scripts/level-audit.mts N` proves every surface is reachable.

