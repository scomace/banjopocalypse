// WORLD 1 — THE HOLLER. 11 original layouts, gentle ramp. These levels are
// the motif exemplars for the whole game: porch tiers, creek gaps, updraft
// chimneys, one mechanic per level, boss bowl at 11.
// Grid: 30 wide x 17 tall. See levels/types.ts for symbols.
//
// THE TIER GRID — read this before editing any layout.
// Bubble Bobble's contract with the player is "every floor is exactly one jump
// above the one below it." Ours is the same, expressed as a hard grid:
//
//     row 16  the floor
//     row 13  tier 1   \
//     row 10  tier 2    |  3 rows = 96px apart. The weakest jumper in the
//     row  7  tier 3    |  cast rises 118px, so every step has ~22px of slack.
//     row  4  tier 4    |
//     row  1  tier 5   /   (attic levels only)
//
// Platforms go ONLY on those rows, and every tier must overlap — or sit within
// ~2 columns of — a tier one step below it, or the player is stranded on the
// floor watching enemies come to them. Spawn markers (a-d, J, S) go on the row
// directly ABOVE their platform so the thing spawns planted on it; player
// spawns go on row 15 so they start standing on the floor.
//
// Anything 4+ rows up is deliberate: that is what bubbles are for. Ride one to
// climb, or bounce off one (hold jump on contact) for a ~5 tile launch.
//
// `npx tsx scripts/level-audit.mts 1` proves every surface is reachable.

